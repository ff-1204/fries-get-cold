// FF-1204 — 개구부 너머의 가게. **마지막 구간(도착)에서만 보인다** (setShopNear).
//
// 왜 '들어가는 방'이 아니라 '들여다보이는 내부'인가:
//   game.md 스코프 원칙이 "맵은 골목 구간 5개 재활용, 신규 씬 없음"이고,
//   v0.11.0 결정이 "가는 길은 컷, 튀김은 밖에 나온 명분으로만"이다.
//   그래서 거래는 컷으로 남기되, **목적지가 간판이 아니라 장소**가 되게 한다 —
//   예전에는 터널을 숨기면 개구부 너머가 빈 하늘이었다 (v0.11.32에서 발견).
//
// 광원을 새로 만들지 않는다: `shopGlow`(z=-L-6)가 이미 여기 있고,
// setShopNear가 near일 때 30으로 올린다 — 그 자리가 정확히 가게 안이다 (visual-polish §4).
//
// ---------- ⭐⭐ 한옥으로 지었다 (v0.11.65 — 요청) ----------
// 이 골목은 콘크리트 빌라촌이다. 그 끝에 **목조 기와집이 하나** 서 있으면,
// 목적지가 '간판이 큰 가게'가 아니라 **다른 종류의 건물**이 된다 —
// 실루엣이 다르므로 멀리서, 어두워도, 글씨를 못 읽어도 구분된다.
//
// 무엇으로 한옥을 만드는가 (전부 박스 + 캔버스 텍스처, 에셋 0 유지):
//   ① **기와지붕** — 두 물매가 용마루에서 만난다. 이 골목에서 유일한 사선이다
//   ② **처마와 서까래** — 지붕이 벽보다 앞으로 나오고 그 밑에 서까래가 줄지어 드러난다.
//      한옥을 한옥으로 만드는 것은 지붕 색이 아니라 **처마 밑의 그 그늘**이다
//   ③ **창호(한지 문살)** — 이 가게의 웜을 담당한다. 기름 표면이 점이라면 창호는 **면**이다
//   ④ **나무 기둥 + 주춧돌** — 돌 위에 나무가 선다. 콘크리트 골목에 없는 이음이다
//   ⑤ **툇마루** — 카운터 앞의 낮은 나무 단
// ⚠ 안쪽(카운터·튀김기·메뉴판)은 그대로 둔다 — 실측으로 잡은 시야 관계가 거기 걸려 있고
//   (v0.11.33 메뉴판 잘림), 가게의 **정체는 튀김집**이지 한옥집이 아니다.
//   한옥인 것은 **껍데기**다: 오래된 한옥에 요즘 튀김집이 들어온 것으로 읽히면 맞다

import * as THREE from 'three';
import {
  boxOf, concrete, surfaceMat, menuTexture, stampBoardTexture, shopSignTexture, hoursTexture,
  giwaTexture, hanjiTexture,
} from './kit';
import { L } from './layout';

/** 가게 전면(카운터)의 z. 구간 통과 판정이 -40.5에서 걸리므로 그 2m 뒤 —
 *  걸음이 멈추는 자리에서 카운터가 정면에 온다 */
const FRONT_Z = -L - 6.6;

/** @param standalone 간판과 등을 **제 안에** 갖는다. 앞(퇴근길 도착) 인스턴스는 골목이 가진
 *  `shopSign`·`shopGlow`를 빌려 쓰지만, 뒤(밤의 출발점) 인스턴스는 그럴 게 없다.
 *  그룹 안에 넣으면 숨겼을 때 three가 서브트리째 건너뛰므로 **안 보이는 동안 광원 비용이 0**이다 */
export function buildShopFront(standalone = false): THREE.Group {
  const g = new THREE.Group();
  const M = {
    road: concrete(0x181c28),      // 가게 앞 바닥 — 골목과 같은 아스팔트
    wall: concrete(0x232838),      // 이웃 가게 벽 (골목 벽과 같은 콘크리트)
    shutter: concrete(0x2a3143),   // 닫힌 셔터
    tile: concrete(0x6e6a5e),      // 가게 안쪽 타일 — 밝다 (웜 조명을 받는 면)
    steel: concrete(0x8a8e96),     // 스테인리스 — 튀김기·카운터
    dark: concrete(0x141922),      // 후드·틀
    awning: concrete(0x7c1d22),    // 휘장 — 현수막과 같은 붉은색
    wood: concrete(0x4a3527),      // 기둥·서까래·툇마루 — 오래된 목재
    woodDark: concrete(0x2e2119),  // 도리·문틀 — 그늘에 든 목재
    stone: concrete(0x585a5c),     // 주춧돌 — 다듬은 화강암
  };
  // 기름 표면 — 이 가게의 심장. 광원 없이 발광만으로 따뜻하다 (웜 = 안전·목표, §3)
  const oilMat = new THREE.MeshStandardMaterial({
    color: 0xffb23e, emissive: 0xffb23e, emissiveIntensity: 0.55, roughness: 0.4,
  });
  // ⭐ 기와 — 넓은 면이라 **몸체색은 거의 무채색**으로 두고 질감만 텍스처가 낸다
  //   (visual-polish: 넓은 면은 무채색, 색은 작은 면이 낸다). 한색 쪽으로 살짝 민 회청색.
  // ⚠ 물매마다 반복 수가 다르다 — 폭은 같고 길이가 다르므로 `surfaceMat`을 따로 부른다
  //   (BoxGeometry는 모든 면이 0~1 UV라 한 재질을 돌려쓰면 짧은 쪽 기와가 늘어난다)
  const giwa = giwaTexture();
  const GIWA_C = 0x2f3542;
  // ⭐ 창호 — **이 가게의 웜을 담당하는 면**이다. `emissiveMap`이 한지 부분만 빛내고
  //   살(나무)은 검게 남아 격자가 실루엣으로 선다. 광원이 아니라 발광이므로 비용은 0이다.
  // ⚠ 0.45를 넘기지 않는다 — 기름 표면(0.55)보다 밝으면 가게의 심장이 바뀐다
  const hanji = hanjiTexture();
  const hanjiMat = new THREE.MeshStandardMaterial({
    map: hanji, emissiveMap: hanji, emissive: 0xffffff, emissiveIntensity: 0.45, roughness: 0.92,
  });

  // ---------- 가게 앞 작은 마당 ----------
  // y를 골목 바닥(-0.1)보다 낮춘다 — 같은 높이면 겹치는 구간에서 z-파이팅이 난다.
  // 겹치지 않는 곳(z < -43)에서만 드러나고, 플레이어는 -40.5에서 멈추므로 단차는 안 보인다
  boxOf(M.road, 12, 0.2, 12, 0, -0.18, FRONT_Z + 3.4, g);

  // ---------- 가게 껍데기 ----------
  const W = 8;                      // 가게 폭 (개구부 2.8보다 넓다 — 다 보이지는 않는다)
  const D = 3.6;                    // 안쪽 깊이
  const backZ = FRONT_Z - D;
  boxOf(M.tile, W, 3.4, 0.2, 0, 1.7, backZ, g);                       // 안쪽 뒷벽
  for (const s of [-1, 1]) {
    boxOf(M.tile, 0.2, 3.4, D, s * (W / 2), 1.7, FRONT_Z - D / 2, g);  // 안쪽 옆벽
  }
  boxOf(M.dark, W + 0.4, 0.25, D, 0, 3.5, FRONT_Z - D / 2, g);         // 천장
  // 전면 상인방(창방) — 개방된 앞면의 위쪽을 막는다. 한옥에서는 기둥 위를 잇는 가로재다
  boxOf(M.woodDark, W + 0.4, 1.1, 0.4, 0, 3.0, FRONT_Z, g);

  // ---------- ⭐ 창호(교창) — 상인방 자리의 빛나는 격자 ----------
  // 한옥은 문 위에 **교창**(가로로 긴 살창)을 둔다. 그 자리가 마침 이 가게에서
  // **개구부(반폭 1.4)로 들여다볼 때 정면에 오는 높이**다 (메뉴판·영업시간과 같은 띠).
  // ⭐ 멀리서 이 가게를 찾게 하는 것이 이 면이다: 골목 끝의 **따뜻한 가로띠 하나**.
  //   글씨가 아니라 빛이라 안개 너머에서도, 깊은 밤에도 남는다
  const shoji = new THREE.Mesh(new THREE.PlaneGeometry(W - 0.6, 0.86), hanjiMat);
  shoji.position.set(0, 3.02, FRONT_Z + 0.21);
  g.add(shoji);
  // 안쪽 옆벽에도 한 짝씩 — 개구부로 비스듬히 들여다볼 때 안이 따뜻하다.
  // ⚠ 벽 안쪽면(±(W/2−0.1))에서 0.02만 띄운다. 같은 면이면 z-파이팅으로 지글거린다
  for (const s of [-1, 1]) {
    const side = new THREE.Mesh(new THREE.PlaneGeometry(1.5, 1.25), hanjiMat);
    side.position.set(s * (W / 2 - 0.12), 2.05, FRONT_Z - D / 2);
    side.rotation.y = -s * Math.PI / 2;
    g.add(side);
  }

  // ---------- ⚠⚠ 붉은 휘장을 걷어냈다 (v0.11.65) ----------
  // 옛 차양(붉은 판)의 **현수막과 같은 붉은색**을 처마 밑 천으로 이어받으려 했다. 두 번 옮겼고
  // 두 번 다 안 됐다 — 그리고 실패의 이유가 하나였다:
  //   ① 처마 **안쪽**(y 3.2~3.4)에 걸면 서까래가 같은 자리로 내려와 나무를 뚫는다
  //   ② 처마 **바깥**(z −40.45)으로 빼면 서까래는 피하지만 **가게 광원(z −42)이 안 닿는다** —
  //      실측 스크린샷에서 붉은 천이 아니라 **현판 위의 검은 막대**로 나왔다
  // ⭐ 여기서 배운 것: **처마는 빛의 경계다.** 처마 밖으로 나간 물건은 색을 잃고 실루엣만 남는다.
  //   색으로 일해야 하는 물건은 처마 안에, 실루엣으로 일할 물건만 밖에 둔다.
  // ⭐ 그래서 붉은색은 **골목의 현수막**이 혼자 맡는다. 가게 쪽 웜은 창호가 이미 하고 있고,
  //   화면에는 붉은 막대가 하나 줄어든 만큼 처마선이 선명해졌다.
  // ⚠ 되살릴 거라면 `boxOf(M.awning, W+0.2, 0.5, 0.06, 0, 2.85, FRONT_Z+2.15)`에
  //   **emissive를 주어** 처마 밖에서도 색이 남게 해야 한다

  // ---------- 카운터 ----------
  boxOf(M.steel, W - 1.0, 1.05, 0.7, 0, 0.525, FRONT_Z - 0.5, g);
  boxOf(M.tile, W - 0.8, 0.08, 0.85, 0, 1.09, FRONT_Z - 0.5, g);       // 상판
  // ---------- ⭐ 카운터 위 (v0.11.61) — 사람이 방금까지 일하던 자리로 읽히게 ----------
  // 상판(윗면 y 1.13)이 텅 비어 있었다. 물건 몇 개가 놓여 있으면 **비어 있는 것이 아니라
  // 잠깐 비운 것**이 된다 — 이 가게는 새벽에도 열려 있고, 그게 밤 1 에필로그의 단서다.
  // ⚠ 전부 카운터 위(y 1.13~1.35)라 개구부(반폭 1.4)로 들여다보는 시야에 들어온다
  boxOf(M.dark, 0.46, 0.05, 0.34, -1.0, 1.16, FRONT_Z - 0.42, g);      // 트레이 (기름종이 깐)
  boxOf(M.dark, 0.46, 0.05, 0.34, -0.45, 1.16, FRONT_Z - 0.55, g);
  boxOf(M.tile, 0.3, 0.42, 0.22, 1.15, 1.34, FRONT_Z - 0.5, g);        // 포장 봉투 더미
  boxOf(M.steel, 0.11, 0.2, 0.11, 1.62, 1.23, FRONT_Z - 0.44, g);      // 소금통
  boxOf(M.steel, 0.11, 0.2, 0.11, 1.8, 1.23, FRONT_Z - 0.48, g);       // 후춧통
  // 주문 대기 스툴 둘 — 카운터 **앞**(마당 쪽). 앉을 자리가 있는 가게는 잠깐 머무는 곳이 된다
  for (const sx of [-2.1, 2.35]) {
    boxOf(M.steel, 0.36, 0.06, 0.36, sx, 0.62, FRONT_Z + 0.85, g);     // 좌판
    for (const d of [-1, 1]) {
      boxOf(M.steel, 0.05, 0.62, 0.05, sx + d * 0.13, 0.31, FRONT_Z + 0.85, g);
    }
  }

  // ---------- 튀김기 두 조 — 기름이 빛난다 ----------
  for (const s of [-1, 1]) {
    boxOf(M.steel, 1.25, 0.95, 0.85, s * 1.5, 1.5, backZ + 0.75, g);
    const oil = new THREE.Mesh(new THREE.BoxGeometry(1.02, 0.05, 0.62), oilMat);
    oil.position.set(s * 1.5, 1.99, backZ + 0.75);
    g.add(oil);
    boxOf(M.steel, 0.06, 0.5, 0.06, s * 1.5, 2.25, backZ + 1.1, g);    // 건짐망 손잡이
    // ⭐ **건짐망 자체** (v0.11.61) — 손잡이만 있고 망이 없었다. 기름 위에 걸쳐 둔 망 하나가
    //   "지금 튀기는 중"과 "치워 둔 가게"를 가른다. 한쪽은 기름 안, 한쪽은 걸이에 올려 둔다
    boxOf(M.dark, 0.62, 0.07, 0.44, s * 1.5, s > 0 ? 2.02 : 2.14, backZ + 0.72, g);
  }
  boxOf(M.dark, 3.6, 0.55, 1.1, 0, 2.75, backZ + 0.75, g);             // 후드
  // 후드에서 올라가는 배기 — 천장까지 닿는 세로 요소. 주방이 건물에 연결된 것이 된다
  boxOf(M.dark, 0.6, 0.62, 0.6, 0, 3.28, backZ + 0.75, g);

  // ---------- 벽면 — 메뉴판·도장판·선반 ----------
  const menu = new THREE.Mesh(
    new THREE.PlaneGeometry(2.7, 1.0),
    new THREE.MeshStandardMaterial({ map: menuTexture(), roughness: 0.9 }),
  );
  // **앞쪽 상인방에 매단다** — 안쪽 벽에 붙이면 후드가 가려 가격이 잘렸다 (v0.11.33 실측).
  // 카운터 너머로 걸린 메뉴판은 포장마차의 실제 문법이기도 하다
  menu.position.set(-1.5, 1.92, FRONT_Z - 0.25); // 상인방 아래(2.45)에 딱 걸리게 — 위가 잘리지 않는다
  g.add(menu);

  // 영업시간 안내 — 메뉴판 **맞은편**에, 같은 높이·같은 면에. 골목 개구부(반폭 1.4)로
  // 들여다보는 시야 안에 메뉴판과 함께 들어온다. 밤 1 에필로그의 "왜 24시간을 하지"가
  // 여기서 나온다 — 대사가 아니라 가게에 붙어 있는 것을 읽고 하는 말이어야 한다
  const hours = new THREE.Mesh(
    new THREE.PlaneGeometry(1.15, 0.62),
    new THREE.MeshStandardMaterial({ map: hoursTexture(), roughness: 0.9 }),
  );
  hours.position.set(1.85, 1.92, FRONT_Z - 0.25);
  g.add(hours);
  const stamps = new THREE.Mesh(
    new THREE.PlaneGeometry(0.72, 0.9),
    new THREE.MeshStandardMaterial({ map: stampBoardTexture(), roughness: 0.95 }),
  );
  stamps.position.set(2.6, 1.75, backZ + 0.11);
  g.add(stamps);
  for (const y of [2.15, 2.62]) boxOf(M.steel, 2.2, 0.06, 0.34, 2.6, y, backZ + 0.28, g);

  // ---------- 좁은 마당의 양옆 — 이웃 가게는 **전부 닫혀 있다** ----------
  // 마당을 넓게 트면 텅 빈 광장이 된다. 골목 개구부보다 조금 넓은 정도로만 두고,
  // 옆벽 자체를 닫힌 셔터로 만든다 — 열린 곳은 여기뿐이라는 것이 그림으로 읽힌다
  const YARD = 4.6;                 // 마당 반폭 (가게 폭 8의 절반보다 살짝 넓다)
  const yardMid = FRONT_Z + 3.4;
  for (const s of [-1, 1]) {
    boxOf(M.wall, 0.5, 7, 7.6, s * YARD, 3.5, yardMid, g);             // 옆벽
    boxOf(M.shutter, 0.16, 2.4, 5.4, s * (YARD - 0.32), 1.2, yardMid, g);
    for (let i = 0; i < 4; i++) {                                      // 슬랫
      boxOf(M.dark, 0.17, 0.05, 5.4, s * (YARD - 0.32), 0.5 + i * 0.55, yardMid, g);
    }
    // ⚠⚠ **이웃 가게의 붉은 차양을 걷어냈다** (v0.11.65 실측 스크린샷).
    //   기와지붕이 서기 전에는 가게의 붉은 차양과 한 짝이었는데, 지붕이 들어오자
    //   화면 좌우 상단에 **정체 불명의 붉은 사선 둘**로만 남았다 — 처마의 앙곡과 각도가
    //   부딪히고, 이 골목에서 저채도 적은 이상현상 전용색이라 눈이 먼저 그리로 갔다.
    //   ⭐ 붉은색은 이제 **가게의 휘장 하나**가 맡는다 (현수막과의 색 연결도 그쪽이면 충분하다).
    //   되살릴 거라면 `boxOf(M.awning, 0.9, 0.1, 5.6, s*(YARD−0.6), 2.75, yardMid)` +
    //   `rotation.z = s * −0.24` 였다
  }
  // ---------- ⭐⭐ 기와지붕 (v0.11.65) ----------
  // 여기 있던 것은 **위층 콘크리트 벽**(W+6 × 4.2 × 0.6 @ y 5.5)과 어두운 창 셋이었다.
  // 그것이 하던 일은 둘인데 — ① 개구부 슬롯 위로 보이던 하늘을 막고 ② '골목 안의 가게'로
  // 읽히게 하고 — ①은 뒤로 물린 벽이 그대로 맡고, ②는 **지붕이 더 잘한다.**
  //
  // ⚠⚠ **개구부는 세로로 뚫린 전체 높이 슬롯이다** (prefab.ts 끝벽: x ±1.4 밖으로만 벽이 있고
  //   높이는 벽 전체다). 그래서 가게 위가 비면 하늘이 그대로 보인다 (v0.11.32 실측).
  //   ⭐ 지붕만으로는 못 막는다 — 용마루(y 5.5) 위가 열린다. 그래서 **어두운 벽을 용마루 뒤로
  //   물려** 남겨 둔다: 눈높이(1.6) → 용마루(5.5) 시선을 이어 보면 z −45.6에서 y 6.7이라
  //   벽 윗선(7.6) 안에 든다. 앞에서는 지붕에 가려 안 보이고, 하늘만 막는다
  // ⚠⚠ **플레이어는 처마 밑으로 들어오지 않는다** (v0.11.65 실측). 도착 컷신이
  //   z −36.21에서 걸리므로 이 가게는 **개구부 너머 6.4m 밖에서, 올려다보는 각도로만** 보인다.
  //   그래서 지붕은 **윗면이 아니라 밑면과 실루엣**으로 승부해야 한다:
  //     · 눈높이 1.65 → 용마루(y 6.1, z −44.4) 시선은 위로 28°다. 기와를 깐 **윗면은 영원히 안 보인다**
  //     · 대신 처마 **밑면**이 화면의 그 자리를 차지한다 → 밑면을 서까래가 드러난 어두운 나무로
  //     · 그리고 하늘(또는 밝은 벽)과 만나는 **처마선**이 이 집의 얼굴이다 → 양끝을 들어 올린다
  //   ⭐ 기와 텍스처는 윗면에만 남긴다 — 관리자 비행과 나중의 높은 시점을 위한 것이고 비용은 0이다
  const RIDGE_Y = 6.1;
  const RIDGE_Z = FRONT_Z - D / 2;      // 용마루는 집의 한가운데
  const EAVE_Y = 3.45;
  const EAVE_Z = FRONT_Z + 2.0;         // ⭐ 처마가 벽보다 2m 나온다 — 한옥의 그 그늘
  // ⚠ 폭은 마당 옆벽 안쪽면(±4.35) 안에 둔다. 더 넓히면 **지붕이 옆벽을 관통한다**
  const ROOF_W = 8.6;
  // ---------- 뒷벽 — **용마루 밑에 숨는다** ----------
  // ⚠⚠ 여기 있던 위층 콘크리트 벽(y 3.4~7.6)의 명분은 "개구부 슬롯 위로 하늘이 보인다"였다
  //   (v0.11.32). ⭐ **지붕이 생긴 지금은 그 명분이 뒤집힌다** — 하늘을 등진 기와지붕이야말로
  //   이 집의 얼굴이고, 뒤에 밝은 슬래브가 서 있으면 그 실루엣이 죽는다.
  // ⚠ 실측으로 두 번 틀렸다: `M.wall`은 노을 앰비언트(2.8)에 씻겨 거의 흰 슬래브가 됐고,
  //   `M.dark`로 낮춰도 **용마루 위로 삐져나온 윗변이 크림색 띠**로 남았다.
  //   ⭐ 답은 색이 아니라 높이였다 — **윗변을 용마루(6.1) 밑(6.0)에 두어 지붕에 가린다.**
  //   가게 뒷벽(3.4) 위의 빈 구간만 막으면 되므로 y 3.0~6.0이면 충분하다
  boxOf(M.dark, W + 6, 3.0, 0.6, 0, 4.5, RIDGE_Z - 1.2, g);

  const fdz = EAVE_Z - RIDGE_Z;         // 3.8
  const fdy = RIDGE_Y - EAVE_Y;         // 2.65 → 물매 34.9°, 한옥의 그 기울기
  const RAFTER_A = Math.atan2(fdy, fdz);
  const giwaMat = surfaceMat(GIWA_C, giwa, ROOF_W / 0.34, Math.hypot(fdz, fdy) / 0.9);
  // ⚠ 면 순서 [+X, −X, +Y, −Y, +Z, −Z] — **윗면만 기와, 밑면은 나무**다.
  //   한옥의 처마 밑은 기와가 아니라 **연등천장**(서까래가 그대로 드러난 나무)이고,
  //   여기서는 그 밑면이 화면에 실제로 보이는 유일한 면이다
  const front = new THREE.Mesh(
    new THREE.BoxGeometry(ROOF_W, 0.34, Math.hypot(fdz, fdy)),
    [M.woodDark, M.woodDark, giwaMat, M.woodDark, M.woodDark, M.woodDark],
  );
  front.position.set(0, (EAVE_Y + RIDGE_Y) / 2, (EAVE_Z + RIDGE_Z) / 2);
  front.rotation.x = RAFTER_A;               // +z 끝(처마)이 내려간다
  g.add(front);
  // 뒤 물매 — 앞에서는 안 보이지만, 없으면 용마루가 **끝이 잘린 판**이 된다 (관리자 비행에서 확인)
  const bdz = 2.6;
  const bdy = 1.8;
  const back = new THREE.Mesh(
    new THREE.BoxGeometry(ROOF_W, 0.34, Math.hypot(bdz, bdy)),
    surfaceMat(GIWA_C, giwa, ROOF_W / 0.34, Math.hypot(bdz, bdy) / 0.9),
  );
  back.position.set(0, RIDGE_Y - bdy / 2, RIDGE_Z - bdz / 2);
  back.rotation.x = -Math.atan2(bdy, bdz);
  g.add(back);
  // 용마루 — 두 물매가 만나는 마루. 두툼한 가로 덩어리 하나가 지붕을 '한 채'로 묶는다
  boxOf(M.woodDark, ROOF_W + 0.1, 0.4, 0.66, 0, RIDGE_Y + 0.14, RIDGE_Z, g);

  // ---------- ⭐⭐ 처마선 — 양끝이 들린다 (앙곡) ----------
  // **한옥의 실루엣은 이 한 줄이다.** 수평으로 곧게 끝나면 아무리 기와를 깔아도 창고 지붕이고,
  // 양끝이 위로 들리는 순간 한옥이 된다. 곡선을 만들 수 없으므로(박스뿐) 끝에서
  // **꺾인 조각 하나씩**으로 근사한다 — 실루엣에서는 곡선과 꺾임이 거의 구분되지 않는다.
  // ⚠ `rotation.z`는 local +x를 +y로 올린다. 오른쪽(+x)은 바깥이 +x라 `+`,
  //   왼쪽은 바깥이 local −x라 `−`가 되어야 **양쪽 다 바깥이 들린다** (부호를 s로 묶는다)
  for (const s of [-1, 1]) {
    const up = boxOf(M.woodDark, 1.7, 0.3, 0.62, s * 3.75, EAVE_Y - 0.02, EAVE_Z, g);
    up.rotation.z = s * 0.30;
  }
  // 처마 끝(막새) — 기와가 끝나는 선. 어두운 가로선이 처마의 **아랫변**을 그린다.
  // ⚠ 밝은 돌색으로 뒀더니 콘크리트 인방으로 읽혔다 (실측) — 지붕과 같은 계열로 내린다
  boxOf(M.woodDark, ROOF_W + 0.1, 0.22, 0.28, 0, EAVE_Y - 0.1, EAVE_Z + 0.02, g);

  // ---------- ⭐ 서까래 — 처마 밑에 드러난 나무 ----------
  // 밑면이 이 가게에서 실제로 보이는 지붕 면이므로, 여기의 반복이 곧 '한옥'이다.
  // ⚠ **밑면(woodDark)보다 밝은 나무**로 둔다 — 같은 톤이면 어둠 대 어둠이라 아무것도 안 보인다
  //   (H-015 검은 구멍에서 배운 것과 같다: 어두운 것으로 어둠을 이길 수 없다)
  // ⚠ 물매와 같은 각도로 눕힌다 — 수평으로 두면 처마 밑에 낀 파이프가 된다
  for (let i = 0; i < 9; i++) {
    const r = boxOf(M.wood, 0.17, 0.17, 2.4, -3.6 + i * 0.9, 3.82, EAVE_Z - 1.0, g);
    r.rotation.x = RAFTER_A;
  }

  // ---------- ⭐ 기둥과 주춧돌 — 돌 위에 나무가 선다 ----------
  // 콘크리트 골목에 **없는 이음**이다. 처마를 받치는 것이 보이면 지붕이 떠 있지 않다.
  // ⚠ x ±3.85 — 개구부 시야(반폭 1.4) 밖이라 카운터를 가리지 않는다
  for (const s of [-1, 1]) {
    boxOf(M.stone, 0.46, 0.36, 0.46, s * 3.85, 0.11, FRONT_Z + 0.05, g);
    boxOf(M.wood, 0.26, 2.73, 0.26, s * 3.85, 1.65, FRONT_Z + 0.05, g);
  }

  // 툇마루 — 카운터 앞의 낮은 나무 단. 주문 스툴이 이 위에 앉는다.
  // ⚠ 앞끝 z −40.85는 걸음이 멎는 자리(−40.5)에서 0.35m 앞이다 — 몸으로 부딪히지 않는다
  boxOf(M.wood, 6.4, 0.16, 1.3, 0, 0.0, FRONT_Z + 1.1, g);

  // ---------- 뒤 인스턴스 전용: 제 간판과 제 등 ----------
  if (standalone) {
    // 밤의 출발점에서 돌아보면 **이게 켜져 있어야** 한다 — 방금 나온 곳이라는 증거
    const tex = shopSignTexture('감자튀김 전문점!!\nff-1204');
    const signMat = new THREE.MeshStandardMaterial({
      color: 0xffffff, map: tex, emissiveMap: tex, emissive: 0xffffff,
    });
    const side = concrete(0x140d05);
    // ⚠⚠ **옛 자리(y 4.3, z FRONT_Z+0.55)는 이제 지붕 속이다** — 앞 물매가 그 z에서
    //   y 3.85~4.75를 지나므로 간판이 기와에 박힌다 (v0.11.65 한옥 전환).
    // ⭐ **처마 밑에 매단다 — 현판**이다. 한옥의 이름은 처마 밑 편액에 걸리고,
    //   마침 그 자리가 처마 그늘 안이라 글자의 발광이 배경과 가장 크게 벌어진다.
    // ⚠ 폭 3.4 → 2.6: 뒤의 창호(교창)가 양옆으로 남아야 **빛나는 띠 위에 걸린 판**이 된다.
    //   판이 띠를 다 덮으면 온기가 사라지고 그냥 간판 하나가 된다
    const sign = new THREE.Mesh(
      new THREE.BoxGeometry(2.6, 0.72, 0.22),
      [side, side, side, side, signMat, side],   // 글자는 앞면(+Z)에만
    );
    // ⚠ y 2.9 · z FRONT_Z+1.32에서는 **서까래 앞끝이 판 윗변을 갉았다** (실측 스크린샷:
    //   'ff-1204'의 윗줄이 어두운 막대에 잘렸다). 0.2 내리고 0.25 앞으로 뺀다
    sign.position.set(0, 2.7, FRONT_Z + 1.57);
    g.add(sign);

    // shopGlow와 같은 자리·같은 색. 강도만 한 단 낮다 —
    // 여기는 **두고 온 곳**이지 목표가 아니다 (웜 10%: 도착지가 더 밝아야 한다, §3)
    const glow = new THREE.PointLight(0xffb23e, 20, 26, 2);
    glow.position.set(0, 3, FRONT_Z + 0.6);
    g.add(glow);
  }

  g.visible = false;
  return g;
}
