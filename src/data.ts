// ---------- 스테이지 = 밤 N (docs/stages.md) ----------
// 밤마다 달라지는 것만 여기 있다. 모든 밤에 같은 것(코어 규칙·판정 임계값·확률식·공간·
// 등급)은 config.ts와 spec.md의 몫 — 어느 쪽인지는 stages.md §1 경계표가 정한다.

export interface StageDef {
  night: number;
  /** 온보딩 보장 — 퇴근길 튜토리얼 · 첫 구간 강제 정상 · 무이상 방지 · 조작 힌트를
   *  한 묶음으로 켠다. 규칙을 텍스트로 설명하지 않는 대신 첫 밤의 **구조**가 가르친다
   *  (무설명 학습 — game-design-theory §6) */
  onboarding: boolean;
  /** 가게를 나서며 — 그 밤의 목적을 한 번 말한다 */
  intro: string;
  /** 집에 도착해서 — 그 밤의 마지막 컷 (Peak-End의 End, story.md §5) */
  epilogue: string;
  /** 걸으면서 뜨는 모놀로그 (v0.11.45). 없으면 인트로 한 줄뿐이다.
   *
   *  ⚠ **밤을 걷는 68.9초 동안 자막이 인트로 하나뿐이었다.** 튜토리얼에는 걸음에 맞춰
   *  다섯으로 나뉜 자막(`TEXT.tutBeats`)이 있는데 정작 본게임에는 없었다 —
   *  주인공의 목소리가 밤마다 첫 3초에만 있었다는 뜻이다. 3막 아치(낯섦→홀림→벗어남)는
   *  인트로·에필로그 두 줄로 지기에는 무거우므로, 걸음 중간이 그 무게를 나눠 진다.
   *
   *  `at` = 그 밤의 몇 번째 구간인가(0부터). **`-1`은 마지막 구간** —
   *  늘어남으로 총 구간이 늘어나도 "다 와간다"는 말이 엉뚱한 데서 뜨지 않는다.
   *  `z`는 구간 로컬 좌표(입구 0 → 출구 -36). 장소를 특정하는 문장은 쓰지 않는다:
   *  늘어남이 나면 같은 `at`이 다른 테마에서 뜰 수 있다 */
  beats?: Array<{ at: number; z: number; text: string }>;
  /** 그 밤의 압력 (v0.11.44). 없으면 0 — 밤 1~2는 지금까지와 완전히 같다.
   *
   *  ⚠ **이것은 이전 설계의 번복이다.** 여태 "난이도는 밤 번호를 타지 않는다"가 의도였고,
   *  깊어지는 감각은 해금되는 콘텐츠가 만든다고 봤다. 그런데 실제로는 인트로·에필로그를 빼면
   *  **밤 5가 밤 2와 기계적으로 똑같이 걸렸다** — 다섯 밤짜리 공포 게임에서 마지막 밤이
   *  두 번째 밤과 같은 압력이면 그건 다섯 밤이 아니라 한 밤을 다섯 번 하는 것이다.
   *  콘텐츠 해금만으로는 상승이 안 만들어진다는 것이 확인됐으므로 압력을 데이터로 준다. */
  pressure?: {
    /** 이상 등장 확률에 더한다 (기본식: 0.4 + 경과분×0.06, 상한 0.8) */
    chanceBonus?: number;
    /** 증식 하한 — 늘어남이 없어도 이 밤은 처음부터 동시 이상이 이만큼 많다.
     *  **규칙이 다른 것부터 뽑히므로**(main.ts rollSegment) 1 이상이면
     *  흔적+형체가 함께 서는 것이 그 밤의 기본값이 된다 = "고민"이 상시화된다 */
    swarmFloor?: number;
  };
}

/** 그 밤의 압력 — 없는 필드는 0 (밤 1~2는 압력 0이 정상이다) */
export function pressureOf(night: number): { chanceBonus: number; swarmFloor: number } {
  const p = stageOf(night).pressure ?? {};
  return { chanceBonus: p.chanceBonus ?? 0, swarmFloor: p.swarmFloor ?? 0 };
}

export const STAGES = stagesJson as StageDef[];

/** 기획된 밤의 수 = **방문 도장 칸 수**. 이 수를 넘기면 도장은 칸 밖에 찍힌다
 *  (story.md §2 — 다섯 밤의 디제틱 표시). 칸 수를 바꾸려면 stages.json에 밤을 더한다 */
export const STAGE_COUNT = STAGES.length;

/** 밤 N의 스테이지. **배열을 넘어가면 마지막 스테이지를 재사용한다** —
 *  밤 6+는 엔딩 전 무한 모드이고, 그 반복 규칙은 데이터가 아니라 시스템의 것이다
 *  (stages.md §4). 엔딩이 구현되면 이 클램프는 사라진다 */
export function stageOf(night: number): StageDef {
  return STAGES[Math.min(Math.max(night, 1), STAGE_COUNT) - 1];
}

