/** 통과 규칙 (v0.11.0) — 괴담의 존재마다 대응이 다르다. 이 게임의 판단 축.
 *  gaze  = 흔적·사물: 다가가서 똑바로 봐야 사라진다. 안 보고 나가면 접힘
 *  avert = 사람 형태: 눈을 마주치면 붙잡힌다(접힘). 보지 말고 그냥 지나가야 한다 */
export type AnomalyRule = 'gaze' | 'avert';

export interface AnomalyDef {
  id: string;
  night: number;      // 등장 시작 밤
  /** 배치 구간 1~5 — 구간 테마의 사물에만. 0 = 전 구간 (스폰 포인트 랜덤 출현형) */
  segment: number;
  category: 'OBJ' | 'LGT' | 'TXT' | 'HUM' | 'SPC' | 'SND' | 'MTA';
  /** 통과 규칙 — 관례상 OBJ=gaze / HUM=avert 지만, 데이터가 최종 결정한다 (콘텐츠는 데이터) */
  rule: AnomalyRule;
  effect: AnomalyEffect;
  /** 접힘 직후 암시 문구 (design-principles §3 — 공정성) */
  reveal: string;
  /** 가는 길 전용 — 귀갓길에는 보이지 않는 사물(버거집 간판 등)에 지정 (공정성) */
  outboundOnly?: boolean;
}

